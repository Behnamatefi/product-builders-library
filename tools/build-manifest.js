#!/usr/bin/env node
/* ============================================================================
   tools/build-manifest.js — (re)generate assets/library.js from the pages
   ----------------------------------------------------------------------------
   Idempotent, run it any time. It scans every migrated book page
   (NN - Group/slug.html), reads the meta block out of its inline Book.mount(DATA)
   call, and rewrites assets/library.js — the manifest that powers the library
   navigation header (prev/next + the "all books" overlay).

   Run this after you ADD a new book page or CHANGE a book's title/group:
       node tools/build-manifest.js

   (For the original one-shot migration from the legacy self-contained pages,
   see tools/migrate.js — that tool is NOT idempotent and should not be re-run.)
   ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

const manifest = [];
fs.readdirSync(ROOT)
  .filter(d => /^\d\d - /.test(d) && fs.statSync(path.join(ROOT, d)).isDirectory())
  .sort()
  .forEach(dir => fs.readdirSync(path.join(ROOT, dir))
    .filter(f => f.endsWith('.html')).sort()
    .forEach(f => {
      const html = fs.readFileSync(path.join(ROOT, dir, f), 'utf8');
      const m = html.match(/Book\.mount\((\{[\s\S]*\})\);\s*<\/script>/);
      if (!m) { console.warn(`  ⚠ ${dir}/${f}: no Book.mount(DATA) — skipped`); return; }
      let data;
      try { data = JSON.parse(m[1]); }
      catch (e) { console.warn(`  ⚠ ${dir}/${f}: DATA not valid JSON — skipped (${e.message})`); return; }
      const meta = data.meta || {};
      manifest.push({
        slug: meta.slug || f.replace(/\.html$/, ''),
        folder: meta.folder || dir,
        groupNum: meta.groupNum || parseInt(dir, 10),
        group: meta.group || { en: dir.replace(/^\d\d - /, ''), fa: '' },
        book: meta.book || { en: f, fa: '' }
      });
    }));

manifest.sort((a, b) => a.groupNum - b.groupNum || a.slug.localeCompare(b.slug));

const out = `/* ============================================================================
   library.js — manifest of all ${manifest.length} books (generated by tools/build-manifest.js)
   Drives the library navigation header: prev/next + the "all books" overlay.
   Regenerate with:  node tools/build-manifest.js
   ========================================================================== */
window.LIBRARY = ${JSON.stringify(manifest, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, 'assets', 'library.js'), out, 'utf8');
console.log(`Wrote assets/library.js with ${manifest.length} books.`);
